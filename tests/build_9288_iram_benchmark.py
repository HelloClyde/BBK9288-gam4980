#!/usr/bin/env python3
"""Build the BBK 9288 external-RAM versus IRAM benchmark."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import build_9288  # noqa: E402


BUILD = ROOT / "build" / "iram-benchmark"
PAYLOAD_SECTION = ".iram_benchmark_payload"
PAYLOAD_SYMBOL = "g_iram_benchmark_payload"
PAYLOAD_SIZE_MACRO = "IRAM_BENCHMARK_PAYLOAD_SIZE"
MAX_PAYLOAD_SIZE = 128


def run(command: list[str]) -> None:
    print("+", " ".join(command))
    subprocess.run(command, check=True)


def capture(command: list[str]) -> str:
    print("+", " ".join(command))
    return subprocess.check_output(command, text=True)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--sdk", type=Path, required=True)
    parser.add_argument("--toolchain", type=Path, required=True)
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "build" / "9288-IRAM-BENCH.exe",
    )
    parser.add_argument(
        "--quick",
        action="store_true",
        help="build a short functional-check variant for the emulator",
    )
    return parser.parse_args()


def write_payload_header(data: bytes, path: Path) -> None:
    lines = [
        "/* Generated by build_9288_iram_benchmark.py. */",
        "#ifndef BBK9288_IRAM_BENCHMARK_PAYLOAD_H",
        "#define BBK9288_IRAM_BENCHMARK_PAYLOAD_H",
        "",
        f"#define {PAYLOAD_SIZE_MACRO} {len(data)}u",
        f"static const u8 {PAYLOAD_SYMBOL}[{PAYLOAD_SIZE_MACRO}] = {{",
    ]
    for offset in range(0, len(data), 12):
        chunk = data[offset:offset + 12]
        lines.append("    " + ", ".join(f"0x{byte:02x}u" for byte in chunk) + ",")
    lines.extend(("};", "", "#endif", ""))
    path.write_text("\n".join(lines), encoding="ascii")


def main() -> None:
    args = parse_args()
    BUILD.mkdir(parents=True, exist_ok=True)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    include = BUILD / "sdk-include"
    generated = BUILD / "generated"
    generated.mkdir(parents=True, exist_ok=True)
    build_9288.prepare_sdk_headers(args.sdk.resolve(), include)
    toolchain = args.toolchain.resolve()
    clang = build_9288.find_tool(toolchain, "clang")
    objcopy = build_9288.find_tool(toolchain, "llvm-objcopy")
    objdump = build_9288.find_tool(toolchain, "llvm-objdump")
    readelf = build_9288.find_tool(toolchain, "llvm-readelf")
    flags = [
        "--target=s1c33-none-elf",
        "-O2",
        "-ffreestanding",
        "-fno-builtin",
        "-fno-jump-tables",
        "-fno-unwind-tables",
        "-fno-asynchronous-unwind-tables",
        "-fomit-frame-pointer",
        "-fdata-sections",
        "-ffunction-sections",
        "-fno-strict-aliasing",
        "-Wall",
        "-Wextra",
        "-Werror",
        "-Wno-pointer-to-int-cast",
        "-Wno-int-to-pointer-cast",
        "-DDL_DOWN",
        "-D_RLS_",
        "-I",
        str(ROOT / "src" / "9288_compat"),
        "-I",
        str(include),
        "-I",
        str(ROOT / "src"),
    ]
    if args.quick:
        flags.extend((
            "-DIRAM_BENCH_BATCHES=8u",
            "-DIRAM_BENCH_ITERATIONS_PER_BATCH=64u",
        ))

    payload_object = BUILD / "9288_iram_benchmark_payload.o"
    run([
        clang, *flags, "-c",
        str(ROOT / "tests" / "9288_iram_benchmark_payload.c"),
        "-o", str(payload_object),
    ])
    relocations = capture([readelf, "-r", str(payload_object)])
    if "There are no relocations" not in relocations:
        raise SystemExit("IRAM payload is not position independent:\n" + relocations)
    payload_raw = BUILD / "iram_benchmark_payload.bin"
    run([
        objcopy, "-O", "binary", f"--only-section={PAYLOAD_SECTION}",
        str(payload_object), str(payload_raw),
    ])
    payload = payload_raw.read_bytes()
    if not payload or len(payload) > MAX_PAYLOAD_SIZE:
        raise SystemExit(f"unexpected IRAM payload size: {len(payload)}")
    header = generated / "9288_iram_benchmark_payload.h"
    write_payload_header(payload, header)
    disassembly = capture([objdump, "-d", str(payload_object)])
    (BUILD / "iram_benchmark_payload.dis.txt").write_text(
        disassembly, encoding="utf-8"
    )

    sources = [
        ROOT / "src" / "gam4980_9288_start.c",
        ROOT / "src" / "gam4980_9288_runtime.c",
        ROOT / "tests" / "9288_iram_benchmark.c",
    ]
    objects: list[Path] = []
    for source in sources:
        output = BUILD / f"{source.stem}.o"
        run([
            clang, *flags, "-I", str(generated),
            "-c", str(source), "-o", str(output),
        ])
        objects.append(output)

    elf = BUILD / "IRAM_BENCH.elf"
    map_path = BUILD / "IRAM_BENCH.map"
    run([
        clang,
        "--target=s1c33-none-elf",
        "-fuse-ld=lld",
        "-nostdlib",
        "-Wl,--gc-sections",
        f"-Wl,-T,{ROOT / 'src' / 'gam4980_9288.ld'}",
        f"-Wl,-Map,{map_path}",
        *(str(item) for item in objects),
        "-o", str(elf),
    ])
    raw = BUILD / "IRAM_BENCH.bin"
    run([objcopy, "-O", "binary", "--gap-fill", "255", str(elf), str(raw)])
    app_payload = raw.read_bytes()
    payload_end = build_9288.read_map_symbol(map_path, "__payload_end")
    expected = payload_end - build_9288.APP_LOAD_ADDRESS
    if len(app_payload) != expected:
        raise SystemExit(f"payload size {len(app_payload)} != expected {expected}")

    app = bytearray(build_9288.pack_kf2(app_payload))
    app[12:28] = b"IRAM_BENCH".ljust(16, b"\0")
    args.output.write_bytes(app)
    print(f"IRAM payload: {len(payload)} bytes, {payload.hex()}")
    print(f"built: {args.output.resolve()}")
    print(f"size: {len(app)}")
    print(f"sha256: {hashlib.sha256(app).hexdigest()}")


if __name__ == "__main__":
    main()
